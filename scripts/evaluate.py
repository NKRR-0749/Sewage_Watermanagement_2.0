"""
Evaluate the plant and its AI, and write results/EVALUATION.md

    python scripts/evaluate.py
    python scripts/evaluate.py --norms moefcc2017_metro

Takes about 30 seconds (the whole month is simulated three times).
"""

import argparse
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from stp import DISCHARGE_NORMS  # noqa: E402
from stp.evaluation import full_evaluation  # noqa: E402


def md_table(records, columns=None):
    df = pd.DataFrame(records)
    if columns:
        df = df[columns]
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--norms", choices=list(DISCHARGE_NORMS), default="ngt2019")
    args = p.parse_args()

    print("Simulating the demo month in all three modes...")
    r = full_evaluation(norms=args.norms)

    fa = r["false_alarms"]
    report = f"""# Evaluation results

Generated by `python scripts/evaluate.py`. Norms: **{DISCHARGE_NORMS[args.norms]['label']}**.
Data: the built-in demo month (SIMULATED July influent, 720 hours, 9 labelled shock events).
The ML models were trained on a separate normal-only month and never saw this one.

## 1. Autonomous agents vs a conventional plant

{md_table(r['modes'], ['mode', 'hours_meeting_norms_pct', 'volume_meeting_norms_pct', 'violation_hours', 'worst_parameter', 'energy_kwh', 'chlorine_kg', 'diverted_m3', 'overflow_m3'])}

DO control error (mean distance from the 2.0 mg/L target): {r['do_tracking_error']}

## 2. Anomaly detection, graded against the true event labels

Share of each event's hours that each detector flagged:

{md_table(r['detection'])}

False alarms on {fa['normal_hours']} normal hours: rules {fa['rules']}, ML {fa['ml']}, AI mode (either) {fa['ai_mode']}.

Overall scores (event hours vs normal hours):

{md_table([dict(detector=k, **v) for k, v in r['detector_scores'].items()])}

## 3. ML forecast vs "same as last hour"

{md_table(r['forecast'])}

## What this shows (and does not show)

- The big gain comes from agents that ACT: diverting shocks, correcting pH, controlling
  oxygen, nitrate recycle and chlorine. A plant with fixed settings fails most hours.
- The rule-based and ML detectors are complementary. Rules catch anything that breaks a
  known limit (e.g. pH). The Isolation Forest catches unusual combinations that break no
  single rule (the food-waste event), but misses shocks in one parameter that it was not
  trained to look at separately (acid/alkaline dumps). That is why AI mode uses both.
- The forecaster beats "same as last hour" for flow; for BOD and ammonia it is no better,
  because the equalization tank already smooths those.
- All of this is on SIMULATED influent built from typical Indian values, with simplified
  process formulas. It demonstrates the control logic; it is not a validated plant model.
"""
    out = os.path.join(ROOT, "results")
    os.makedirs(out, exist_ok=True)
    path = os.path.join(out, "EVALUATION.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(report)
    print(report)
    print(f"Saved to {path}")


if __name__ == "__main__":
    main()
