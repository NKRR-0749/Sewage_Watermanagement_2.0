"""
Evaluate the plant and its AI, and write results/EVALUATION.md

    python scripts/evaluate.py
    python scripts/evaluate.py --norms moefcc2017_metro

    python scripts/evaluate.py --quick        # 3 random months instead of 10

Takes about 5 minutes (about 100 simulated months in total).
"""

import argparse
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from stp import DISCHARGE_NORMS  # noqa: E402
from stp.config import OPERATOR_DELAY_HOURS  # noqa: E402
from stp.evaluation import (full_evaluation, multi_month, unseen_events,  # noqa: E402
                            divert_policy_test, operator_delay_sensitivity)
from stp.ml import get_models  # noqa: E402


def md_table(records, columns=None):
    df = pd.DataFrame(records)
    if columns:
        df = df[columns]
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def update_summary(out, key, value):
    """Key figures for the dashboard's start screen (results/summary.json)."""
    import json
    path = os.path.join(out, "summary.json")
    data = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    data[key] = value
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--norms", choices=list(DISCHARGE_NORMS), default="ngt2019")
    p.add_argument("--quick", action="store_true", help="fewer random months (faster)")
    args = p.parse_args()
    n_months, n_unseen = (3, 2) if args.quick else (10, 5)

    print("1/5  Demo month in all four modes...")
    r = full_evaluation(norms=args.norms)
    print(f"2/5  {n_months} random months...")
    mm = multi_month(n_months, args.norms)
    print(f"3/5  {n_unseen} months of unseen shock types...")
    un = unseen_events(n_unseen, args.norms)
    print("4/5  Operator response delay...")
    delay = operator_delay_sensitivity(norms=args.norms)
    print("5/5  Diversion policy test...")
    policy = divert_policy_test(4 if args.quick else 8, 2 if args.quick else 4, args.norms)
    fc_check = get_models()[1].validation

    fa = r["false_alarms"]
    report = f"""# Evaluation results

Generated by `python scripts/evaluate.py{' --quick' if args.quick else ''}`. Norms: **{DISCHARGE_NORMS[args.norms]['label']}**.
All data in this file is SIMULATED (see results/EVALUATION_REAL.md for the real dataset).
The ML models were trained on a separate normal-only month and never saw any test month.

Control modes:
- **ai**: autonomous agents, ML + rule detection, ML forecasting
- **rules**: autonomous agents, rule detection only, "same as last hour" forecasting
- **operator**: a WELL-RUN conventional plant: DO feedback control on the blowers, recycle at
  its design value, and a human operator who diverts shocks, doses pH and switches storm pumping
  after an alarm has lasted {OPERATOR_DELAY_HOURS} hours
- **fixed**: conventional plant with fixed settings; nobody acts on alarms

Raw sewage that overflows the equalization tank is mixed into the discharge before the norms
check, so overflow counts as a violation.

## 1. The demo month (720 h, 9 labelled shock events), four control modes

{md_table(r['modes'], ['mode', 'hours_meeting_norms_pct', 'volume_meeting_norms_pct', 'violation_hours', 'worst_parameter', 'energy_kwh', 'chlorine_kg', 'diverted_m3', 'overflow_m3'])}

DO control error (mean distance from the 2.0 mg/L target): {r['do_tracking_error']}

## 2. Is it a lucky month? {n_months} random months

Each month has new random sewage AND a new random schedule of 9 shock events.

{md_table(mm['summary'])}

Paired comparison on the same months:

{md_table([mm['ai_vs_rules'], mm['ai_vs_operator']])}

## 3. Shock types the plant was never tuned for ({n_unseen} months)

Solvent discharge (non-biodegradable COD, normal pH), ammonia spike (NH4 x2.2 only) and a slow
30-hour strength drift. None of them appear in the demo month or were used to set any rule or model.

{md_table(un['summary'])}

{md_table([un['ai_vs_rules']])}

Share of each unseen event's hours flagged (mean over months):

{md_table(un['by_event'])}

## 4. Anomaly detection on the demo month, graded against the true labels

Share of each event's hours that each detector flagged:

{md_table(r['detection'])}

False alarms on {fa['normal_hours']} normal hours: rules {fa['rules']}, ML {fa['ml']}, AI mode (either) {fa['ai_mode']}.

{md_table([dict(detector=k, **v) for k, v in r['detector_scores'].items()])}

The ML detector = Isolation Forest (catches unusual combinations) + robust z-score per parameter
(catches single-parameter shocks such as pH 3, which an Isolation Forest alone misses).

## 5. Design checks

**How much of the advantage is speed of response?** Operator mode with different response delays:

{md_table(delay)}

A toxic shock that reaches the bacteria before anyone acts poisons them. Nitrifiers recover over
days, so total nitrogen (TN) fails long after the shock is gone.

**Should the plant divert water on an alarm with no identified cause?** AI mode, same months:

{md_table(policy)}

Diverting on uncertain (mostly ML-only) alarms fills the holding tank with ordinary sewage, which
leaves no room for the next real toxic shock. The plant now reports such alarms but does not divert.

## 6. ML forecast vs "same as last hour"

Self-check on held-out training data (decides which quantities use the ML forecast):
{fc_check}

On the demo month (with shocks):

{md_table(r['forecast'])}

## What this shows (and does not show)

- Fast automatic action is what matters most: agents that divert toxic shocks, correct pH, control
  oxygen, nitrate recycle and chlorine. Even a well-run conventional plant loses most of that
  advantage when its operator needs {OPERATOR_DELAY_HOURS} hours to respond (sections 1, 2 and 5).
- Over many months the ML adds about nothing to compliance on known shock types (section 2):
  the rules already catch them. On shock types the plant was never tuned for, ML detection catches
  much more than the rules (section 3); compliance gains there are small, because the plant's
  feedback controls absorb most of these loads.
- The rule-based and ML detectors are complementary. Rules have no false alarms on the shocks they
  were written for; the ML catches loads no rule describes, at the cost of a few false alarms a month.
- All results here are on SIMULATED influent with simplified process formulas. They show the
  control logic, not a validated plant model.
"""
    out = os.path.join(ROOT, "results")
    os.makedirs(out, exist_ok=True)
    update_summary(out, "simulated", {
        "demo_month": {x["mode"]: x["hours_meeting_norms_pct"] for x in r["modes"]},
        "random_months": {x["mode"]: x["hours_meeting_norms_pct"] for x in mm["summary"]},
        "n_months": n_months,
        "unseen_recall": {x["mode"]: x["detector_recall"] for x in un["summary"] if x["mode"] in ("ai", "rules")},
        "operator_delay_h": OPERATOR_DELAY_HOURS,
    })
    path = os.path.join(out, "EVALUATION.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(report)
    print(report)
    print(f"Saved to {path}")


if __name__ == "__main__":
    main()
