"""
Evaluate the plant on REAL sewage data and write results/EVALUATION_REAL.md

    python scripts/evaluate_real.py               # all 370 test days (~3-5 min)
    python scripts/evaluate_real.py --days 60     # quicker check

Dataset: UCI Water Treatment Plant (Poch, 1993), daily influent of a real
municipal sewage plant in Manresa, Spain. See stp/real_data.py.
"""

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from stp import DISCHARGE_NORMS  # noqa: E402
from stp.evaluation_real import full_real_evaluation  # noqa: E402

sys.path.insert(0, os.path.join(ROOT, "scripts"))
from evaluate import md_table, update_summary  # noqa: E402


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--norms", choices=list(DISCHARGE_NORMS), default="ngt2019")
    p.add_argument("--days", type=int, help="only the first N test days (default: all)")
    args = p.parse_args()

    r = full_real_evaluation(norms=args.norms, days=args.days)
    d = r["data"]
    fa = r["false_alarms"]
    filled = ", ".join(f"{k} {v} days" for k, v in d["missing_values_filled"].items())
    ranges = "\n".join(f"| {k} | {v[0]} | {v[1]} |" for k, v in d["ranges"].items())

    report = f"""# Evaluation on REAL sewage data

Generated by `python scripts/evaluate_real.py{' --days ' + str(args.days) if args.days else ''}`.
Norms: **{DISCHARGE_NORMS[args.norms]['label']}**.

## 0. The dataset

**{d['source']}.** Public, licence CC BY 4.0.
<https://archive.ics.uci.edu/dataset/106/water+treatment+plant>

- {d['days']} days of real daily influent measurements (flow, pH, BOD, COD, suspended solids).
- First **{d['train_days']} days** are used only to train the ML models; the remaining
  **{d['test_days']} days** ({r['test_hours']} hours simulated here) are the test.
- Missing readings filled by interpolation: {filled}.
- Plant-state labels in the data: {d['plant_states']}.
- Flow scaled by {d['flow_scale']} (real median {d['median_flow_m3_day_original']:,} m³/day -> our 10 MLD plant).
  Concentrations are used exactly as measured.
- Not in the dataset and therefore ASSUMED: the hour-by-hour shape inside each day,
  ammonia (estimated from COD), temperature and faecal coliforms (typical values).

Real influent ranges:

| parameter | min | max |
|---|---|---|
{ranges}

Mean real influent: {d['means']} (typical Indian sewage in our simulated data: pH 7.4, BOD 250, COD 475, TSS 300).

## 1. The four control modes on real influent

Site-calibrated: ML trained on the real training days, rule limits tuned to them
(COD/BOD limit {r['rule_limits']['cod_bod']}, TSS limit {r['rule_limits']['TSS']} mg/L; pH limits unchanged).

{md_table(r['modes'], ['setup', 'hours_meeting_norms_pct', 'volume_meeting_norms_pct', 'violation_hours', 'worst_parameter', 'alarms', 'alarm_hours_pct', 'energy_kwh', 'diverted_m3', 'overflow_m3'])}

## 2. Our plant vs the REAL plant's measured effluent (same days, same influent)

The dataset also records what the real Manresa plant discharged. Our plant never sees
these numbers; they are only used for comparison. Daily means of our hourly effluent.

{md_table(r['vs_real_plant'])}

The real plant was a conventional secondary plant (early 1990s). Ours adds nitrogen removal,
a tertiary filter and automatic control, so it should do better; the point of this table is that
our effluent is in a believable range for real sewage, not that the comparison is like-for-like.

## 3. Does site calibration matter?

{md_table(r['calibration'], ['setup', 'hours_meeting_norms_pct', 'violation_hours', 'alarms', 'alarm_hours_pct', 'diverted_m3', 'overflow_m3'])}

How often each rule fires on the real test data:

{md_table(r['rules'])}

## 4. Detectors graded on real data + injected labelled shocks

{r['shock_events']} shock hours were injected on top of the real test data (all six event types,
one event about every 4 days). Real hours count as "normal", so any alarm on a real day counts
as a false alarm. If the real data itself contains unusual days, these scores are pessimistic.

Share of each event's hours flagged (site-calibrated):

{md_table(r['detection'])}

False alarms on {fa['normal_hours']} real hours: rules {fa['rules']}, ML {fa['ml']}, AI mode (either) {fa['ai_mode']}.

**Site-calibrated** (ML trained on real days, calibrated rule limits):

{md_table([dict(detector=k, **v) for k, v in r['detector_scores'].items()])}

**Not calibrated** (ML trained on the simulated month, default Indian rule limits):

{md_table([dict(detector=k, **v) for k, v in r['detector_scores_uncalibrated'].items()])}

## 5. Results in each real plant state (AI mode)

{md_table(r['by_plant_state'])}

## 6. ML forecast vs "same as last hour" (real test days)

{md_table(r['forecast'])}

Note: inside each day the hourly shape is assumed, so part of the forecast's advantage
comes from learning that assumed shape. The day-to-day changes it has to follow are real.

## What this shows (and does not show)

- The plant runs unchanged on real measured sewage from a working municipal plant.
- Real sewage is not the "typical" sewage the plant was designed around. Rule limits tuned
  for Indian domestic sewage and an ML model trained on simulated data raise far too many
  false alarms on a real plant (sections 3 and 4). Calibrating both on the plant's own
  normal days is required, and the project now does this automatically.
- The data has no shock labels, so detection is graded on injected shocks only.
- Treatment is still simulated with simplified process formulas: the real data is the
  INPUT, the effluent is the model's prediction, not a measurement.
"""
    out = os.path.join(ROOT, "results")
    os.makedirs(out, exist_ok=True)
    update_summary(out, "real", {
        "test_days": d["test_days"],
        "modes": {x["setup"]: x["hours_meeting_norms_pct"] for x in r["modes"]},
        "false_alarms_calibrated": r["detector_scores"]["used_by_plant"]["false_alarms"],
        "false_alarms_uncalibrated": r["detector_scores_uncalibrated"]["used_by_plant"]["false_alarms"],
        "real_plant_effluent_COD": next(x["REAL_plant_effluent_mean"] for x in r["vs_real_plant"] if x["parameter"] == "COD"),
        "our_effluent_COD": next(x["our_effluent_mean"] for x in r["vs_real_plant"] if x["parameter"] == "COD"),
    })
    path = os.path.join(out, "EVALUATION_REAL.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(report)
    print(report)
    print(f"Saved to {path}")


if __name__ == "__main__":
    main()
